"""Generate the firmware icon table from the editor's pixel icons."""

from pathlib import Path
import runpy

root = Path(__file__).resolve().parent.parent
icons = runpy.run_path(str(root / "desktop-app/icons.py"))["PIXELS"]
rows = [", ".join(f"0x{pixel:02X}" for pixel in icon) for icon in icons]
header = "// Generated by scripts/generate_editor_icons.py\n#pragma once\n"
header += "static const uint8_t omp_icons[8][8] = {\n"
header += "".join("    {" + row + "},\n" for row in rows) + "};\n"
(root / "keyboards/icst7789v/keymaps/default/cc_editor_icons.h").write_text(header, encoding="utf-8")
